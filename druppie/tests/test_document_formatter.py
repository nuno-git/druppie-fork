"""Tests for the Document Formatter Service.

Covers Typst-based PDF compilation from native .typ source files.
Run these tests after `docker compose --profile dev up -d` (or locally
if typst is installed) to verify the document pipeline.
"""
from __future__ import annotations

import io
import subprocess
from pathlib import Path
from unittest.mock import patch

import pypdf
import pytest

from druppie.services.document_formatter_service import (
    DocumentFormatterError,
    DocumentFormatterService,
)


def _test_input(name: str) -> Path:
    """Return path to a test fixture .typ file."""
    return Path(__file__).parent.parent / "templates" / "documents" / "test-inputs" / f"{name}.typ"


class TestDocumentFormatterFunctional:
    """PDF compilation end-to-end with real Typst engine."""

    def test_service_finds_typst_binary(self):
        """Sanity check that typst binary and template dir resolve."""
        svc = DocumentFormatterService()
        assert svc.typst_bin is not None
        assert Path(svc.typst_bin).exists()

    def test_functioneel_ontwerp_compiles(self):
        """FO .typ → PDF with correct page count and structure."""
        svc = DocumentFormatterService()
        typ_path = _test_input("functional-design")

        pdf_bytes = svc.compile_typ(typ_path)

        assert len(pdf_bytes) > 1000

        reader = pypdf.PdfReader(io.BytesIO(pdf_bytes))
        assert len(reader.pages) >= 3  # Title + TOC + content pages

        full_text = ""
        for page in reader.pages:
            full_text += page.extract_text() or ""
        assert "Inleiding" in full_text
        assert "Inhoudsopgave" in full_text  # TOC generated by template
        assert "Functioneel" in full_text or "Functioneel Ontwerp" in full_text

    def test_technisch_ontwerp_compiles(self):
        """TO .typ with table-heavy content renders."""
        svc = DocumentFormatterService()
        typ_path = _test_input("technical-design")

        pdf_bytes = svc.compile_typ(typ_path)

        assert len(pdf_bytes) > 1000
        reader = pypdf.PdfReader(io.BytesIO(pdf_bytes))
        assert len(reader.pages) >= 3

        full_text = ""
        for page in reader.pages:
            full_text += page.extract_text() or ""
        assert "Architectuur" in full_text
        assert "Data Model" in full_text
        assert "Integratie" in full_text

    def test_draft_watermark_present(self):
        """DRAFT status produces a visible watermark."""
        svc = DocumentFormatterService()
        typ_path = _test_input("functional-design")

        pdf_bytes = svc.compile_typ(typ_path)

        reader = pypdf.PdfReader(io.BytesIO(pdf_bytes))
        first_page = reader.pages[0]
        text = first_page.extract_text() or ""
        assert "DRAFT" in text or "Niet-definitief" in text

    def test_final_no_watermark(self):
        """FINAL status omits the watermark."""
        svc = DocumentFormatterService()
        rel_template = svc.template_dir.relative_to(Path(svc.project_root)) / "rijnland.typ"

        tmp = Path("/app") / "tmp" / "test-final.typ"
        tmp.write_text(
            f'#import "/{rel_template}": rijnland_doc\n\n'
            f'#show: rijnland_doc.with(\n'
            f'  title: "Final Test",\n'
            f'  document_type: "functional_design",\n'
            f'  status: "FINAL",\n'
            f'  project_name: "Test",\n'
            f'  include_toc: false,\n'
            f'  include_watermark: true,\n'
            f'  section_breaks: false,\n'
            f')\n\n'
            f'= Test Section\n\nSome content.\n',
            encoding="utf-8",
        )

        pdf_bytes = svc.compile_typ(tmp)

        reader = pypdf.PdfReader(io.BytesIO(pdf_bytes))
        first_page = reader.pages[0]
        text = first_page.extract_text() or ""
        assert "DRAFT" not in text
        assert "Niet-definitief" not in text.upper()

    def test_invalid_template_path_raises(self):
        """Missing template should raise DocumentFormatterError early."""
        with pytest.raises(DocumentFormatterError):
            DocumentFormatterService(template_dir="/nonexistent/path")

    @pytest.mark.parametrize("doc_type", ["functional_design", "technical_design"])
    def test_all_document_types_compile(self, doc_type):
        """Ensure each supported document_type compiles without error."""
        svc = DocumentFormatterService()
        tmp = Path("/app") / "tmp" / f"test-{doc_type}.typ"
        rel_template = svc.template_dir.relative_to(Path(svc.project_root)) / "rijnland.typ"
        tmp.write_text(
            f'#import "/{rel_template}": rijnland_doc\n\n'
            f'#show: rijnland_doc.with(\n'
            f'  title: "Test Document",\n'
            f'  document_type: "{doc_type}",\n'
            f'  status: "DRAFT",\n'
            f'  project_name: "Test",\n'
            f'  include_toc: false,\n'
            f'  include_watermark: false,\n'
            f'  section_breaks: false,\n'
            f')\n\n'
            f'= Section\n\nSome content.\n',
            encoding="utf-8",
        )
        pdf_bytes = svc.compile_typ(tmp)
        assert len(pdf_bytes) > 100

    def test_verify_typ_reports_syntax_ok(self):
        """verify_typ returns True for a clean .typ file."""
        svc = DocumentFormatterService()
        tmp = Path("/app") / "tmp" / "test-valid.typ"
        rel_template = svc.template_dir.relative_to(Path(svc.project_root)) / "rijnland.typ"
        tmp.write_text(
            f'#import "/{rel_template}": rijnland_doc\n\n'
            f'#show: rijnland_doc.with(title: "OK")\n= Test\n',
            encoding="utf-8",
        )
        is_valid, error = svc.verify_typ(tmp)
        assert is_valid is True
        assert error is None

    def test_verify_typ_reports_syntax_error(self):
        """verify_typ returns False for a broken .typ file."""
        svc = DocumentFormatterService()
        tmp = Path("/app") / "tmp" / "test-invalid.typ"
        tmp.write_text(
            "#broken syntax { UNSPECIFIED\n",
            encoding="utf-8",
        )
        is_valid, error = svc.verify_typ(tmp)
        assert is_valid is False
        assert error is not None

    def test_compile_typ_missing_file(self):
        """compile_typ raises DocumentFormatterError for missing source file."""
        svc = DocumentFormatterService()
        with pytest.raises(DocumentFormatterError, match="not found"):
            svc.compile_typ("/nonexistent/path/test.typ")


class TestDocumentFormatterMocked:
    """Unit tests with mocked subprocess for fast, no-Docker execution.

    These cover the failure branches that integration tests cannot hit
    without actually breaking a real Typst binary.
    """

    def test_typst_binary_not_found_raises(self):
        """Initialising service without typst in PATH raises immediately."""
        with patch(
            "druppie.services.document_formatter_service.shutil.which",
            return_value=None,
        ):
            with pytest.raises(DocumentFormatterError, match="Typst binary not found"):
                DocumentFormatterService()

    def test_compile_typ_subprocess_timeout(self):
        """Typst timeout produces a clear DocumentFormatterError."""
        svc = DocumentFormatterService()
        dummy = Path("/app") / "tmp" / "test-timeout.typ"
        dummy.write_text(
            '#import "/druppie/templates/documents/rijnland.typ": rijnland_doc\n'
            '#show: rijnland_doc.with()\n= A\n',
            encoding="utf-8",
        )
        with patch(
            "druppie.services.document_formatter_service.subprocess.run",
            side_effect=subprocess.TimeoutExpired(cmd="typst", timeout=60),
        ):
            with pytest.raises(DocumentFormatterError, match="timed out"):
                svc.compile_typ(dummy)

    def test_compile_typ_subprocess_failure(self):
        """Typst returning a non-zero exit code surfaces stderr."""
        svc = DocumentFormatterService()
        dummy = Path("/app") / "tmp" / "test-fail.typ"
        dummy.write_text(
            '#import "/druppie/templates/documents/rijnland.typ": rijnland_doc\n'
            '#show: rijnland_doc.with()\n= B\n',
            encoding="utf-8",
        )
        err = subprocess.CalledProcessError(
            returncode=1,
            cmd="typst",
            stderr="error: file not found\n",
        )
        with patch(
            "druppie.services.document_formatter_service.subprocess.run",
            side_effect=err,
        ):
            with pytest.raises(DocumentFormatterError, match="Typst compilation failed"):
                svc.compile_typ(dummy)

    def test_compile_typ_missing_output_pdf(self):
        """If Typst exits 0 but no PDF is created, raise a sensible error."""
        svc = DocumentFormatterService()
        dummy = Path("/app") / "tmp" / "test-no-pdf.typ"
        dummy.write_text(
            '#import "/druppie/templates/documents/rijnland.typ": rijnland_doc\n'
            '#show: rijnland_doc.with()\n= C\n',
            encoding="utf-8",
        )
        fake_path = Path("/app/tmp/nonexistent-output.pdf")
        with patch(
            "druppie.services.document_formatter_service.subprocess.run",
            return_value=subprocess.CompletedProcess(args=[], returncode=0),
        ):
            with pytest.raises(DocumentFormatterError, match="PDF output was not created"):
                svc.compile_typ(dummy, output_pdf_path=fake_path)

    def test_verify_typ_subprocess_timeout(self):
        """verify_typ returns gracefully on timeout."""
        svc = DocumentFormatterService()
        dummy = Path("/app") / "tmp" / "test-verify-timeout.typ"
        dummy.write_text(
            '#import "/druppie/templates/documents/rijnland.typ": rijnland_doc\n'
            '#show: rijnland_doc.with()\n= D\n',
            encoding="utf-8",
        )
        with patch(
            "druppie.services.document_formatter_service.subprocess.run",
            side_effect=subprocess.TimeoutExpired(cmd="typst", timeout=60),
        ):
            is_valid, error = svc.verify_typ(dummy)
            assert is_valid is False
            assert "timed out" in (error or "").lower()
